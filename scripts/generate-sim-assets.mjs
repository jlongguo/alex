// Generates deterministic Gazebo world + Nav2 occupancy map from Alex's canonical TS grid.
// Run npm run build first. Never hand-edit generated world or PGM.
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve, dirname} from 'node:path';
import {MAP, occupied} from '../dist/robot/map.js';

const base=fileURLToPath(new URL('../robotics/ros2/alex_sim/',import.meta.url));
const check=process.argv.includes('--check');
const res=MAP.cellMeters;
if(res!==0.1||MAP.width!==60||MAP.height!==34)throw new Error('MAP_VERSION_CHANGED_REVIEW_WORLD');
const fmt=n=>Number(n.toFixed(4)).toString();
const escapeXml=s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;');
const box=(name,r,height,visual)=>{
  const x=(r.x+(r.w-1)/2)*res,y=(r.y+(r.h-1)/2)*res;
  return `<model name="${escapeXml(name)}"><static>true</static><pose>${fmt(x)} ${fmt(y)} 0 0 0 0</pose><link name="obstacle"><collision name="collision"><pose>0 0 ${fmt(height/2)} 0 0 0</pose><geometry><box><size>${fmt(r.w*res)} ${fmt(r.h*res)} ${fmt(height)}</size></box></geometry></collision><visual name="visual"><pose>0 0 ${fmt(height/2)} 0 0 0</pose><geometry><box><size>${fmt(r.w*res)} ${fmt(r.h*res)} ${fmt(height)}</size></box></geometry><material><ambient>${visual}</ambient><diffuse>${visual}</diffuse></material></visual></link></model>`;
};
const obstacles=[...MAP.walls.map((r,i)=>box(`wall_${i}`,r,0.45,'0.47 0.58 0.70 1')),...MAP.furniture.map((r,i)=>box(`furniture_${i}`,r,0.32,'0.63 0.45 0.27 1'))].join('\n    ');
const world=`<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by scripts/generate-sim-assets.mjs from src/robot/map.ts; do not edit. -->
<sdf version="1.9">
  <world name="alex_home">
    <gravity>0 0 -9.8</gravity>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors"><render_engine>ogre2</render_engine></plugin>
    <light name="sun" type="directional"><pose>0 0 8 0 0 0</pose><diffuse>0.8 0.8 0.8 1</diffuse><specular>0.2 0.2 0.2 1</specular><attenuation><range>30</range><constant>0.7</constant><linear>0.01</linear><quadratic>0.001</quadratic></attenuation><direction>-0.5 -0.3 -1</direction></light>
    <model name="floor"><static>true</static><pose>${fmt((MAP.width-1)*res/2)} ${fmt((MAP.height-1)*res/2)} -0.05 0 0 0</pose><link name="base"><collision name="collision"><geometry><box><size>${fmt(MAP.width*res)} ${fmt(MAP.height*res)} 0.1</size></box></geometry></collision><visual name="visual"><geometry><box><size>${fmt(MAP.width*res)} ${fmt(MAP.height*res)} 0.1</size></box></geometry><material><ambient>0.8 0.81 0.78 1</ambient><diffuse>0.8 0.81 0.78 1</diffuse></material></visual></link></model>
    ${obstacles}
    <!-- The model:// path is resolved by GZ_SIM_RESOURCE_PATH in launch. -->
    <include><uri>model://alex_bot</uri><name>alex_bot</name><pose>${fmt(MAP.destinations.dock.x*res)} ${fmt(MAP.destinations.dock.y*res)} 0 0 0 0</pose></include>
  </world>
</sdf>
`;
// P2 plain PGM; image y=0 is top row, ROS occupancy origin is bottom-left.
const pixels=[];
for(let row=MAP.height-1;row>=0;row--){
  pixels.push(Array.from({length:MAP.width},(_,col)=>occupied(col,row)?'0':'254').join(' '));
}
const pgm=`P2\n# Alex home occupancy, generated from canonical map; 0 occupied, 254 free\n${MAP.width} ${MAP.height}\n255\n${pixels.join('\n')}\n`;
const yaml=`# GENERATED by scripts/generate-sim-assets.mjs; origin is ROS lower-left.\nimage: alex_home.pgm\nmode: trinary\nresolution: ${res}\norigin: [0.0, 0.0, 0.0]\nnegate: 0\noccupied_thresh: 0.65\nfree_thresh: 0.25\n`;
const assets=[['worlds/alex_home.sdf',world],['maps/alex_home.pgm',pgm],['maps/alex_home.yaml',yaml]];
for(const [name,contents] of assets){
  const path=resolve(base,name);
  if(check){if(readFileSync(path,'utf8')!==contents)throw new Error(`SIM_ASSET_OUT_OF_SYNC: ${name} (run npm run sim:generate)`);}
  else{mkdirSync(dirname(path),{recursive:true});writeFileSync(path,contents);}
}
console.log(check?'Alex simulation assets match the TypeScript map':'Generated Alex Gazebo world + Nav2 map');
